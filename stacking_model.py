"""
stacking_model.py
=================
Production-grade Stacked Ensemble for Carbon Biomass Estimation.

Architecture
------------
Level 0 (Base Learners) : RandomForest | XGBoost | SVR
Level 1 (Meta-Learner)  : Ridge Regression

The meta-model is trained exclusively on Out-of-Fold (OOF) predictions
generated by the base learners, preventing target leakage and ensuring
the final model generalises to unseen environments.

Author : <Your Name>
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from datetime import datetime
from typing import Dict, List, Optional, Tuple

import joblib
import numpy as np
import pandas as pd
from sklearn.base import clone
from sklearn.ensemble import RandomForestRegressor
from sklearn.impute import SimpleImputer
from sklearn.linear_model import Ridge
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import GridSearchCV, KFold, train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVR
from xgboost import XGBRegressor


# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

RAW_FEATURES: List[str] = [
    "clay",
    "sand",
    "silt",
    "elev",
    "annual_precip",
    "peat_frac",
    "Hydraulic_Stress",
    "NDVI",
]

DERIVED_FEATURES: List[str] = ["precip_clay_interaction"]

MODEL_FEATURES: List[str] = RAW_FEATURES + DERIVED_FEATURES

TARGET: str = "AGB"

BASE_MODEL_NAMES: List[str] = ["RF", "XGB", "SVR"]


# ---------------------------------------------------------------------------
# Data Layer
# ---------------------------------------------------------------------------


class BiomassDataHandler:
    """
    Handles data ingestion, feature engineering, imputation, and scaling.

    All preprocessing artefacts (imputer, scaler) are fitted on the training
    partition only and persisted so the same transforms can be applied at
    inference time without re-fitting.

    Parameters
    ----------
    file_path : str
        Absolute path to the CSV containing the labelled dataset.
    features : list[str]
        Ordered list of feature column names used during model training.
    target : str
        Name of the response / target column.
    """

    def __init__(self, file_path: str, features: List[str], target: str) -> None:
        self.file_path = file_path
        self.features = features
        self.target = target
        self.imputer = SimpleImputer(strategy="mean")
        self.scaler = StandardScaler()
        self.df: Optional[pd.DataFrame] = None

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def load(self) -> pd.DataFrame:
        """Load CSV from *file_path* and cache in ``self.df``."""
        if not os.path.exists(self.file_path):
            raise FileNotFoundError(f"Dataset not found at: {self.file_path}")

        self.df = pd.read_csv(self.file_path)
        print(f"[BiomassDataHandler] Loaded {len(self.df):,} records.")
        return self.df

    def engineer_features(self) -> None:
        """
        Create derived interaction features from raw covariates.

        Adds the following columns in-place:
        - ``precip_clay_interaction`` : annual_precip × clay
        """
        if self.df is None:
            raise RuntimeError("Call .load() before engineering features.")

        self.df["precip_clay_interaction"] = (
            self.df["annual_precip"] * self.df["clay"]
        )
        print("[BiomassDataHandler] Feature engineering complete.")

    def get_full_data(self) -> Tuple[pd.DataFrame, pd.Series]:
        """Return raw (un-scaled) X and y for the full dataset."""
        if self.df is None:
            self.load()
        return self.df[self.features].copy(), self.df[self.target].copy()

    def prepare_split(
        self,
        X_train_raw: Optional[pd.DataFrame] = None,
        X_test_raw: Optional[pd.DataFrame] = None,
        test_size: float = 0.2,
    ) -> Tuple[np.ndarray, np.ndarray, pd.Series, pd.Series]:
        """
        Impute and scale feature matrices, fitting transforms on the training
        partition exclusively.

        Parameters
        ----------
        X_train_raw, X_test_raw : optional DataFrames
            If provided, these are preprocessed directly (for nested CV use).
            If omitted, a fresh random split is performed.
        test_size : float
            Fraction of the dataset reserved for testing (default 0.20).

        Returns
        -------
        X_train_sc, X_test_sc : np.ndarray
        y_train, y_test : pd.Series
        """
        if X_train_raw is not None and X_test_raw is not None:
            y_train = self.df.loc[X_train_raw.index, self.target]
            y_test = self.df.loc[X_test_raw.index, self.target]
        else:
            X_full, y_full = self.get_full_data()
            X_train_raw, X_test_raw, y_train, y_test = train_test_split(
                X_full, y_full, test_size=test_size, random_state=42
            )

        X_tr = X_train_raw[self.features]
        X_te = X_test_raw[self.features]

        # Fit transforms on training data only – prevents leakage
        X_train_sc = self.scaler.fit_transform(self.imputer.fit_transform(X_tr))
        X_test_sc = self.scaler.transform(self.imputer.transform(X_te))

        self.y_train = y_train
        self.y_test = y_test

        return X_train_sc, X_test_sc, y_train, y_test


